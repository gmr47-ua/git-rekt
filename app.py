def tr_dato(v):
    if st.session_state.get("lang") != "en":
        return v
    if isinstance(v, list):
        return [tr_dato(x) for x in v]
    if isinstance(v, str):
        if v in TRAD_DATOS:
            return TRAD_DATOS[v]
        m = RE_DESC.match(v)
        if m:
            return (f"Exploratory detection of possible new water across the full common coverage of the "
                    f"GeoTIFFs from {m.group(1)} and {m.group(2)}; not limited to Paiporta.")
    return v


