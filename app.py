def fecha_legible(iso):
    """'2024-10-19' -> '19 oct 2024' (es) / '19 Oct 2024' (en). Si no se puede interpretar, devuelve el texto tal cual."""
    meses = MESES_EN if st.session_state.get("lang") == "en" else MESES
    try:
        a, m, d = str(iso).split("-")
        return f"{int(d)} {meses[int(m) - 1]} {a}"
    except (ValueError, IndexError):
        return str(iso) if iso else t("fecha_nd")


